// Generates a deterministically seeded 128D unit vector descriptor for a student
function generateSeededDescriptor(seed: number): number[] {
  const vec: number[] = [];
  let s = seed;
  for (let i = 0; i < 128; i++) {
    // Linear congruential generator for reproducible unique biometric signatures
    s = (s * 9301 + 49297) % 233280;
    const val = (s / 233280.0) * 2 - 1;
    vec.push(val);
  }
  // Normalize vector to unit length (L2 norm)
  const norm = Math.sqrt(vec.reduce((acc, v) => acc + v * v, 0));
  return vec.map((v) => Number((v / norm).toFixed(6)));
}

